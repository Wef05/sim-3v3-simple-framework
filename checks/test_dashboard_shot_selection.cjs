const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('tools/tactics_dashboard/dashboard.js','utf8');
const lines=[],ctx={$:()=>({replaceChildren(){lines.length=0}}),line:(_,s)=>lines.push(s),pointText:JSON.stringify};
vm.createContext(ctx);
vm.runInContext(source.slice(source.indexOf('function renderAttackChoice('),source.indexOf('function validBlockPoint(')),ctx);
const option={id:'goal_0',kind:'shot',target:[7,-1.05],interception_probability:.2,raw_probability:.8,penalty:.1,probability:.7,excluded_reason:null};
const choice={enabled:true,model:'shot_edge_penalty',evaluated_at:0,selected:option,options:[option],runner_up:null,margin:null,actual_target:option.target,execution:'shot'};
assert.ok(ctx.validAttackChoice(choice));
const render=()=>{ctx.renderAttackChoice({context:{now:.2},players:[{role:'attack',attack_choice:choice}]});return lines.join('\n')};
assert.match(render(),/原始成功 80.0% − 10 个百分点 = 70.0%/);
choice.selected=null;choice.actual_target=[7,0];
assert.match(render(),/中央射门兜底/);
choice.actual_target=null;choice.execution='blocked_stop';
assert.match(render(),/结构阻挡，停止/);
console.log('Shot score, center fallback, blocked execution and replay schema passed.');
